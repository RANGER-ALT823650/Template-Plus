"""Extract the flat plateau vectors from Apple's retained drawing, sheet 1 Detail D.
Run with pdfplumber. Hole positions/diameters use the annotations, not the artwork.
The drawing scale is calibrated by the two left lens centers (14.37 and 33.61 mm).
"""
from pathlib import Path
import json, hashlib, math
import pdfplumber
root=Path(__file__).resolve().parent.parent
# Ordered boundary fragments. Gaps are the straight top/bottom/side edges.
specs={
 'iphone-17-pro': dict(parts=[346,339,340,342,343,345], lens=[398,338], middle=32.36, right=58.03, camera=16.20,mic=1.05,flash=6.80,sensor=6.65,body=[71.95,150.01]),
 'iphone-17-pro-max':dict(parts=[422,424,426,427,419,420],lens=[279,282],middle=32.36,right=64.16,camera=16.20,mic=1.15,flash=6.80,sensor=6.65,body=[77.99,163.43]),
 'iphone-18-pro':dict(parts=[382,383],bottom=[380,381],lens=[419,416],middle=32.49,right=58.03,camera=16.58,mic=1.15,flash=6.90,sensor=6.90,body=[71.95,150.01]),
 'iphone-18-pro-max':dict(parts=[348,349,350,351],lens=[343,340],middle=32.49,right=64.16,camera=16.58,mic=1.15,flash=6.90,sensor=6.90,body=[77.99,163.43]),
}
result={}
for model,s in specs.items():
 source=root/'assets/phones/sources'/f'{model}.pdf'
 p=pdfplumber.open(source).pages[1]
 def pts(i):
  assert all(op[0] in ['m','l'] for op in p.curves[i]['path'])
  return [op[1] for op in p.curves[i]['path']]
 def center(i):
  c=p.curves[i];return ((c['x0']+c['x1'])/2,(c['top']+c['bottom'])/2)
 cx,cy=center(s['lens'][0]);_,cy2=center(s['lens'][1])
 scale=(cy2-cy)/(33.61-14.37)
 fragments=[pts(i) for i in s['parts']]
 if 'bottom' in s:
  bottom=[pts(i) for i in s['bottom']]
  # The original right lower fragments are partially occluded by annotation
  # lines. Reflect the intact left fragments about the flat surface midline.
  axis=(min(x for a in fragments for x,y in a)+max(x for a in fragments for x,y in a))/2
  fragments += [[(2*axis-x,y) for x,y in a] for a in bottom]+bottom
 # Order fragments around the surface, then orient each toward its successor.
 # Nearest-fragment stitching is ambiguous across the long straight top edge.
 midx=(min(x for a in fragments for x,y in a)+max(x for a in fragments for x,y in a))/2
 midy=(min(y for a in fragments for x,y in a)+max(y for a in fragments for x,y in a))/2
 fragments.sort(key=lambda a:math.atan2(sum(y for x,y in a)/len(a)-midy,sum(x for x,y in a)/len(a)-midx))
 ordered=[]
 for i,a in enumerate(fragments):
  nxt=fragments[(i+1)%len(fragments)]
  def distance(pt):return min((pt[0]-q[0])**2+(pt[1]-q[1])**2 for q in [nxt[0],nxt[-1]])
  ordered += a if distance(a[-1])<distance(a[0]) else a[::-1]
 xmin=min(x for x,y in ordered);ymin=min(y for x,y in ordered)
 w=(max(x for x,y in ordered)-xmin)/scale;h=(max(y for x,y in ordered)-ymin)/scale
 origin=[14.37+(xmin-cx)/scale,14.37+(ymin-cy)/scale]
 outer='M '+' L '.join(f'{(x-xmin)/scale:.7f},{(y-ymin)/scale:.7f}' for x,y in ordered)+' Z'
 official=[['camera-1',14.37,14.37,s['camera']],['camera-2',14.37,33.61,s['camera']],['camera-3',s['middle'],23.99,s['camera']],['flash',s['right'],13.82,s['flash']],['microphone',s['right'],23.99,s['mic']],['lidar',s['right'],34.16,s['sensor']]]
 holes=[[n,x-origin[0],y-origin[1],d] for n,x,y,d in official]
 path=outer
 for n,x,y,d in holes:
  r=d/2;path+=f' M {x-r:.7f},{y:.7f} a {r},{r} 0 1 0 {d},0 a {r},{r} 0 1 0 {-d},0 Z'
 plateau=dict(width=w,height=h,outer=outer,path=path,holes=holes,margin=2)
 data=dict(source='https://developer.apple.com/download/files/accessories/dimensional-drawings/'+model+'.pdf',sha256=hashlib.sha256(source.read_bytes()).hexdigest(),source_sheet='1, Detail D; innermost flat-surface vector boundary',boundary_curve_indices=s['parts']+s.get('bottom',[]),symmetry_reconstruction='intact left lower fragments reflected for right lower boundary' if 'bottom' in s else None,scale_calibration='left lens centers Y=14.37 and 33.61 mm',official_holes_name_x_y_diameter_mm=official,derived_flat_top_origin_from_phone_top_left_mm=origin,derived_flat_top_width_height_mm=[w,h],body_drawing_width_height_mm=s['body'],orientation='upright rear view, cameras left, not mirrored',manufacturing_clearance_mm=0,plateau=plateau)
 folder=root/'assets/phones'/model;folder.mkdir(exist_ok=True)
 (folder/'dimensions.json').write_text(json.dumps(data,indent=2)+'\n')
 (folder/'plateau-cutout.svg').write_text(f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}mm" height="{h}mm" viewBox="0 0 {w} {h}"><path d="{path}" fill="#d9dde2" fill-rule="evenodd"/></svg>\n')
 result[model]=dict(plateau=plateau,phone=dict(width=s['body'][0],height=s['body'][1],plateauX=origin[0],plateauY=origin[1]))
 print(model,round(w,4),round(h,4),origin)
(root/'src/pro-geometry.js').write_text('// Generated by scripts/build-pro-plateaus.py from retained Apple PDFs.\nexport const PRO_GEOMETRY='+json.dumps(result,separators=(',',':'))+';\n')
